void CORE::ECS::MeshComponent::load_mesh(const std::string& mesh_type)
{
    if (mesh_type == "cube")
        load_cube();
    else if (mesh_type == "plane")
        load_plane();
    glGenVertexArrays(1, &m_VAO);
    glGenBuffers(1, &m_VBO);
    // fill the data
    glBindBuffer(GL_ARRAY_BUFFER, m_VBO);
    glBufferData(GL_ARRAY_BUFFER, data.size() * sizeof(float), data.data(), GL_STATIC_DRAW);
    // attributes
    glBindVertexArray(m_VAO);
    glEnableVertexAttribArray(0);
    glVertexAttribPointer(0, 3, GL_FLOAT, GL_FALSE, 8 * sizeof(float), (void*)0);
    glEnableVertexAttribArray(1);
    glVertexAttribPointer(1, 3, GL_FLOAT, GL_FALSE, 8 * sizeof(float), (void*)(3 * sizeof(float)));
    glEnableVertexAttribArray(2);
    glVertexAttribPointer(2, 2, GL_FLOAT, GL_FALSE, 8 * sizeof(float), (void*)(6 * sizeof(float)));
    glBindBuffer(GL_ARRAY_BUFFER, 0);
    glBindVertexArray(0);
}

void CORE::ECS::MeshComponent::Render()
{
    glBindVertexArray(m_VAO);
    int x = data.size();
    glDrawArrays(GL_TRIANGLES, 0, vertexNum);
    glBindVertexArray(0);
}

void CORE::ECS::MeshComponent::CreateMeshLuaBind(sol::state& lua)
{
    lua.new_usertype<MeshComponent>(
        "Mesh",
        "type_id", &entt::type_hash<MeshComponent>::value,
        sol::call_constructor,
        sol::factories([]() {return MeshComponent(); }),
        "render", [&](MeshComponent& mesh) {mesh.Render(); }
    );
}
